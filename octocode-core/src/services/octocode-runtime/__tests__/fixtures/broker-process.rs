// Native test fixture: fragmented Host stdio and a controllable agent child.
use std::{io::{self, BufRead, Write}, time::Duration};

fn fragmented(text: &str) {
    let mut out = io::stdout().lock();
    for byte in text.as_bytes() {
        out.write_all(&[*byte]).unwrap();
        out.flush().unwrap();
        std::thread::sleep(Duration::from_millis(1));
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.get(1).map(String::as_str) == Some("--db") {
        std::fs::write("fixture-host-started", "started").unwrap();
        for line in io::stdin().lock().lines() {
            let line = line.unwrap();
            if line.contains("\"method\":\"exit.zero\"") { return; }
            // These controlled fixture requests are generated by JSON.stringify.
            let id = line.split("\"id\":").nth(1).unwrap().split(',').next().unwrap();
            let params = line.split("\"params\":").nth(1).unwrap();
            let params = params.strip_suffix('}').unwrap();
            fragmented(&format!("{{\"id\":{id},\"result\":{params}}}\n"));
        }
    } else {
        let index = args.iter().position(|arg| arg == "--prompt-file").unwrap();
        let prompt = std::fs::read_to_string(&args[index + 1]).unwrap();
        fragmented("{\"type\":\"text\",\"text\":\"中文🙂第一段\"}\n");
        std::thread::sleep(Duration::from_millis(if prompt.contains("long") { 60000 } else { 2500 }));
        fragmented("{\"type\":\"text\",\"text\":\"完整答案✅\"}\n");
    }
}
