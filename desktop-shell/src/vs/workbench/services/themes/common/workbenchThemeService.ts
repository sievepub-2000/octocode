/**
 * Maps a stored `workbench.colorTheme` value onto a theme that still exists.
 *
 * This product ships only the OctoCode themes, so every id the upstream editor
 * used to ship has to land on the OctoCode theme of the same kind. Without this
 * an existing settings.json keeps naming a theme that is no longer installed and
 * the workbench falls back to an unthemed default instead of the product's own
 * look — which reads as the theme being broken rather than as a stale setting.
 *
 * Ids that are not in the table pass through untouched, so third-party themes
 * keep working.
 */
const RETIRED_THEME_IDS: ReadonlyMap<string, string> = new Map([
	// Dark themes that used to ship built in, newest spelling first.
	...(['Dark 2026', 'Dark Modern', 'Default Dark Modern', 'Dark+', 'Default Dark+', 'Visual Studio Dark',
		'Experimental Dark', 'VS Code Dark', 'Abyss', 'Kimbie Dark', 'Monokai', 'Monokai Dimmed',
		'Solarized Dark', 'Tomorrow Night Blue', 'Red',
	].map(id => [id, ThemeSettingDefaults.COLOR_THEME_DARK] as const)),

	...(['Light 2026', 'Light Modern', 'Default Light Modern', 'Light+', 'Default Light+', 'Visual Studio Light',
		'Experimental Light', 'VS Code Light', 'Quiet Light', 'Solarized Light',
	].map(id => [id, ThemeSettingDefaults.COLOR_THEME_LIGHT] as const)),

	['Default High Contrast', ThemeSettingDefaults.COLOR_THEME_HC_DARK],
	['Default High Contrast Light', ThemeSettingDefaults.COLOR_THEME_HC_LIGHT],
]);

export function migrateThemeSettingsId(settingsId: string): string {
	return RETIRED_THEME_IDS.get(settingsId) ?? settingsId;
}

